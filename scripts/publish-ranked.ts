import {readFile,writeFile,rename,mkdir} from 'node:fs/promises';
import {validateDraws,recent15,type Dataset} from '../src/core/data';
import {rankedRecommendations,type Mode} from '../src/core/recommend';
import {dataSignature} from '../src/core/advanced-model';
const data=JSON.parse(await readFile('public/data/lotto.json','utf8')) as Dataset;
const draws=recent15(validateDraws(data.draws));
const full=JSON.parse(await readFile('public/data/full-history.json','utf8')) as Dataset;
const fullDraws=validateDraws(full.draws);
if(fullDraws[0].round!==1||fullDraws.at(-1)!.round!==draws.at(-1)!.round)throw new Error('전체/15년 자료의 마지막 회차가 다릅니다.');
const modes=['all','overdue','integrated'] as Mode[];
const scopes=Object.fromEntries(([['recent15',draws],['all',fullDraws]] as const).map(([scope,rows])=>[scope,{signature:dataSignature([...rows]),firstRound:rows[0].round,lastRound:rows.at(-1)!.round,results:Object.fromEntries(modes.map(mode=>{console.log(`사전 전수 분석: ${scope} / ${mode}`);return [mode,rankedRecommendations([...rows],mode,10,undefined,scope)];}))}]));
await mkdir('public/data',{recursive:true});
await writeFile('public/data/ranked-results.json.tmp',JSON.stringify({version:2,generatedAt:new Date().toISOString(),scopes}));
await rename('public/data/ranked-results.json.tmp','public/data/ranked-results.json');
console.log('사전 분석 저장 완료: 사이트에서 전수 계산 없이 조회합니다.');
